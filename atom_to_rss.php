namespace phpbbmodders\feedlinks;

/**
 * Converts the Atom 1.0 document phpBB builds for its feeds into RSS 2.0.
 *
 * Mapping, per element:
 *  - feed title, alternate link, subtitle, xml:lang, updated
 *      → channel title, link, description, language, lastBuildDate
 *  - feed rel="self" link → atom:link rel="self" (the RSS URL)
 *  - entry title, link, content → item title, link, description
 *  - entry id → guid (phpBB uses the item's permanent URL)
 *  - entry published (else updated) → pubDate
 *  - entry author name → dc:creator (RSS's own author element needs an
 *    e-mail address, which feeds must not expose)
 *  - entry category → category, with the forum URL as its domain
 */
class atom_to_rss
{
	const ATOM_NS = 'http://www.w3.org/2005/Atom';
	const DC_NS = 'http://purl.org/dc/elements/1.1/';
	const XML_NS = 'http://www.w3.org/XML/1998/namespace';

	/**
	 * Convert an Atom document to RSS 2.0
	 *
	 * @param string $atom_xml Atom document as generated by phpBB
	 * @return string RSS 2.0 document
	 * @throws \RuntimeException When the input is not an Atom feed
	 */
	public function convert($atom_xml)
	{
		$atom = new \DOMDocument();

		// No network access and no DTD processing while parsing
		$previous = libxml_use_internal_errors(true);
		$loaded = $atom->loadXML($atom_xml, LIBXML_NONET);
		libxml_clear_errors();
		libxml_use_internal_errors($previous);

		$feed = $loaded ? $atom->documentElement : null;

		if ($feed === null || $feed->namespaceURI !== self::ATOM_NS || $feed->localName !== 'feed')
		{
			throw new \RuntimeException('Not an Atom feed');
		}

		$rss_doc = new \DOMDocument('1.0', 'UTF-8');
		$rss_doc->formatOutput = true;

		$rss = $rss_doc->createElement('rss');
		$rss->setAttribute('version', '2.0');
		$rss->setAttributeNS('http://www.w3.org/2000/xmlns/', 'xmlns:atom', self::ATOM_NS);
		$rss->setAttributeNS('http://www.w3.org/2000/xmlns/', 'xmlns:dc', self::DC_NS);
		$rss_doc->appendChild($rss);

		$channel = $rss_doc->createElement('channel');
		$rss->appendChild($channel);

		$title = $this->child_text($feed, 'title');
		$description = $this->child_text($feed, 'subtitle');

		$this->add_text($channel, 'title', $title);
		$this->add_text($channel, 'link', $this->link_href($feed, 'alternate'));

		// RSS requires a description; fall back to the title
		$this->add_text($channel, 'description', $description !== '' ? $description : $title);

		$language = $feed->getAttributeNS(self::XML_NS, 'lang');
		if ($language !== '')
		{
			$this->add_text($channel, 'language', $language);
		}

		$updated = $this->rss_date($this->child_text($feed, 'updated'));
		if ($updated !== '')
		{
			$this->add_text($channel, 'lastBuildDate', $updated);
		}

		$self = $this->link_href($feed, 'self');
		if ($self !== '')
		{
			$self_link = $rss_doc->createElementNS(self::ATOM_NS, 'atom:link');
			$self_link->setAttribute('href', $self);
			$self_link->setAttribute('rel', 'self');
			$self_link->setAttribute('type', 'application/rss+xml');
			$channel->appendChild($self_link);
		}

		foreach ($this->children($feed, 'entry') as $entry)
		{
			$channel->appendChild($this->convert_entry($rss_doc, $entry));
		}

		return $rss_doc->saveXML();
	}

	/**
	 * Convert one Atom entry to an RSS item
	 *
	 * @param \DOMDocument $rss_doc
	 * @param \DOMElement $entry
	 * @return \DOMElement
	 */
	protected function convert_entry(\DOMDocument $rss_doc, \DOMElement $entry)
	{
		$item = $rss_doc->createElement('item');

		// phpBB sends titles as escaped HTML; RSS titles are plain text
		$title = html_entity_decode($this->child_text($entry, 'title'), ENT_QUOTES | ENT_HTML5, 'UTF-8');
		$this->add_text($item, 'title', $title);

		$link = $this->link_href($entry, 'alternate');
		if ($link !== '')
		{
			$this->add_text($item, 'link', $link);
		}

		// Escaped HTML, the usual RSS form; a CDATA section would break on
		// post text that happens to contain "]]>"
		$this->add_text($item, 'description', trim($this->child_text($entry, 'content')));

		$author = $this->children($entry, 'author');
		if ($author)
		{
			$name = $this->child_text($author[0], 'name');
			if ($name !== '')
			{
				$creator = $rss_doc->createElementNS(self::DC_NS, 'dc:creator');
				$creator->appendChild($rss_doc->createTextNode($name));
				$item->appendChild($creator);
			}
		}

		foreach ($this->children($entry, 'category') as $category)
		{
			$label = $category->getAttribute('label') !== '' ? $category->getAttribute('label') : $category->getAttribute('term');
			$element = $this->add_text($item, 'category', $label);

			if ($category->getAttribute('scheme') !== '')
			{
				$element->setAttribute('domain', $category->getAttribute('scheme'));
			}
		}

		$id = $this->child_text($entry, 'id');
		if ($id !== '')
		{
			$guid = $this->add_text($item, 'guid', $id);
			$guid->setAttribute('isPermaLink', $id === $link ? 'true' : 'false');
		}

		$published = $this->child_text($entry, 'published');
		$date = $this->rss_date($published !== '' ? $published : $this->child_text($entry, 'updated'));
		if ($date !== '')
		{
			$this->add_text($item, 'pubDate', $date);
		}

		return $item;
	}

	/**
	 * Atom child elements of a node with the given name
	 *
	 * @param \DOMElement $parent
	 * @param string $name
	 * @return \DOMElement[]
	 */
	protected function children(\DOMElement $parent, $name)
	{
		$found = [];

		foreach ($parent->childNodes as $node)
		{
			if ($node instanceof \DOMElement && $node->namespaceURI === self::ATOM_NS && $node->localName === $name)
			{
				$found[] = $node;
			}
		}

		return $found;
	}

	/**
	 * Text of the first Atom child element with the given name
	 *
	 * @param \DOMElement $parent
	 * @param string $name
	 * @return string Empty when there is no such element
	 */
	protected function child_text(\DOMElement $parent, $name)
	{
		$children = $this->children($parent, $name);

		return $children ? trim($children[0]->textContent) : '';
	}

	/**
	 * href of the first link with the given relation (no rel means alternate)
	 *
	 * @param \DOMElement $parent
	 * @param string $rel
	 * @return string
	 */
	protected function link_href(\DOMElement $parent, $rel)
	{
		foreach ($this->children($parent, 'link') as $link)
		{
			$link_rel = $link->getAttribute('rel') !== '' ? $link->getAttribute('rel') : 'alternate';

			if ($link_rel === $rel)
			{
				return $link->getAttribute('href');
			}
		}

		return '';
	}

	/**
	 * Append a child element holding escaped text
	 *
	 * @param \DOMElement $parent
	 * @param string $name
	 * @param string $text
	 * @return \DOMElement The new element
	 */
	protected function add_text(\DOMElement $parent, $name, $text)
	{
		$element = $parent->ownerDocument->createElement($name);
		$element->appendChild($parent->ownerDocument->createTextNode($text));
		$parent->appendChild($element);

		return $element;
	}

	/**
	 * Turn an Atom (RFC 3339) date into an RSS (RFC 822) date
	 *
	 * @param string $date
	 * @return string Empty when the date can't be read
	 */
	protected function rss_date($date)
	{
		if ($date === '')
		{
			return '';
		}

		try
		{
			return (new \DateTime($date))->format(DATE_RSS);
		}
		catch (\Exception $e)
		{
			return '';
		}
	}
}
